#!/usr/bin/env bash
# Writes the nginx edge-auth file and the curl header file from the edge secrets in /etc/cvl (hosted/README.md):
#
#   $CVL_ETC/edge-secret            the current secret (required, 600)
#   $CVL_ETC/edge-secret.previous   the previous secret, only while a rotation overlaps (optional, 600)
#
#   $CVL_ETC/edge-auth.conf         map entries for config/nginx/rengine.conf (mounted at /etc/nginx/edge-auth.conf by docker-compose.hosted.yml)
#   $CVL_ETC/edge-header            one "X-CVL-Edge-Auth: <secret>" line for `curl -H @file`, used by the local health checks (scripts/hosted-edge.sh)
#
# nginx compares the header with a map, which is not a constant-time comparison: a remote attacker could in principle learn a secret byte by byte from
# response timing, which is why the secret is a 256-bit random value (not guessable by prefix search over a network at any usable rate) AND the origin
# is firewalled to the edge's address ranges (hosted/README.md, "Threat model"). The file only ever holds secrets of the alphabet A-Z a-z 0-9 _ -,
# so a secret cannot carry anything nginx reads as syntax. nginx also compares map keys without regard to case, which costs a 43-character secret
# about 30 of its 256 bits and nothing else.
#
# Both files are written in place (same inode), so a single-file bind mount follows the change; run `nginx -s reload` in the proxy afterwards
# (cvl-set-edge-secret.sh does). Prints nothing on stdout. Usage: hosted/gen-edge-auth.sh
set -euo pipefail
# shellcheck source=lib/common.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
umask 077

[ $# -eq 0 ] || cvl_die "usage: $0 (no arguments; the secrets are read from $CVL_ETC)"

read_secret() {
  local file=$1 value
  IFS= read -r value <"$file" || true
  value=${value%$'\r'}
  printf '%s' "$value"
}

current_file=$CVL_ETC/edge-secret
previous_file=$CVL_ETC/edge-secret.previous
[ -f "$current_file" ] || cvl_die "$current_file is missing"
current=$(read_secret "$current_file")
cvl_secret_ok "$current" || cvl_die "the current edge secret is not 32 to 128 characters of A-Z a-z 0-9 _ -"

conf=$'# Generated by hosted/gen-edge-auth.sh. Do not edit: it holds the edge secrets of this server.\n'
conf+=$'default 0;\n'
conf+="\"$current\" 1;"$'\n'
if [ -f "$previous_file" ]; then
  previous=$(read_secret "$previous_file")
  if [ -n "$previous" ]; then
    cvl_secret_ok "$previous" || cvl_die "the previous edge secret is not 32 to 128 characters of A-Z a-z 0-9 _ -"
    # nginx matches map keys without regard to case, so two secrets that differ only in case are one entry (and a duplicate key is a configuration error)
    [ "${previous,,}" = "${current,,}" ] || conf+="\"$previous\" 1;"$'\n'
  fi
fi

cvl_private_dir "$CVL_ETC"
cvl_write_in_place "$CVL_ETC/edge-auth.conf" "$conf"
cvl_write_in_place "$CVL_ETC/edge-header" "X-CVL-Edge-Auth: $current"$'\n'
